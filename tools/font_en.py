def glyphs():
    out = {}
    for ch, rows in RAW.items():
        assert len(rows) == 11, ch
        w = max(len(r.rstrip(".")) for r in rows) if any("#" in r for r in rows) else len(rows[0])
        if ch == " ":
            w = 3
        assert w <= 6, (ch, w)
        bits = [0] * 16
        for i, r in enumerate(rows):
            v = 0
            for x, c in enumerate(r):
                if c == "#":
                    v |= 0x80 >> (x + 1)  # column 0 is the left outline column
            bits[TOP + i] = v
        out[ch] = (w, bits)
    return out


def outline(bits):
    """8-neighbour dilation of the ink minus the ink, per row (8-bit rows)."""
    out = []
    for y in range(16):
        acc = 0
        for dy in (-1, 0, 1):
            if 0 <= y + dy < 16:
                r = bits[y + dy]
                acc |= r | (r << 1) | (r >> 1)
        out.append(acc & 0xFF & ~bits[y])
    return out


